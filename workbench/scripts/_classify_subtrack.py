# 2. 构建 sub_track(基于 biz + industry_zl + 关键词打分)
print("\n[2/4] 计算 sub_track...")
master_by_name = {c['name']: c for c in companies}

def classify_subtrack(c):
    """基于 biz + industry_zl + 专利名 → sub_track"""
    main = c.get('trk', '')
    if not main or main not in SUBTRACK_KEYWORDS:
        return ''

    sub_dict = SUBTRACK_KEYWORDS[main]
    if not sub_dict:
        return ''

    biz = c.get('biz', '') or ''
    text = biz  # 经营范围是主信号
    # 也可以加 industry_zl, 但一般 biz 够用

    scores = {}
    for sub_name, kws in sub_dict.items():
        score = sum(1 for kw in kws if kw in text)
        if score > 0:
            scores[sub_name] = score

    if not scores:
        return ''
    return max(scores.items(), key=lambda x: x[1])[0]

sub_count = 0
for c in companies:
    c['sub_track'] = classify_subtrack(c)
    if c['sub_track']:
        sub_count += 1
print(f"  算 sub_track: {sub_count:,}/{len(companies)} ({sub_count*100//len(companies)}%)")

# 3. 计算 customer_ind + supplier_ind(从 relations 聚合客户的 industry_dl)
